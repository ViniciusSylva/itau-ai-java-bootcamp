public class arithmeticOperators {
    
    public static void main(String[] args) {
        System.out.printf("1 + 1 = %d \n", 1 + 1);
        System.out.printf("2 - 1 = %d \n", 2 - 1);
        System.out.printf("2 * 2 = %d \n", 2 * 2);
        System.out.printf("4 / 2 = %d \n", 4 / 2);
        System.out.printf("5 %% 2 = %d \n", 5 % 2);
        System.out.printf("sqrt(0) = %f \n", Math.sqrt(0)); //Raiz quadrada
        System.out.printf("pow(2, 3) = %f \n", Math.pow(2, 3)); //Poteciação

    }

}
